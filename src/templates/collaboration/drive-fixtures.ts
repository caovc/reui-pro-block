function record(
  name: string,
  owner: string,
  type: string,
  size: string,
  modified: string,
  parent: string,
  sharedWith?: string,
): FileRecord {
  return {
    id: `fixture-${parent}-${name}`,
    name,
    owner,
    type,
    size,
    modified,
    parent,
    star: false,
    sharedWith,
  };
}
