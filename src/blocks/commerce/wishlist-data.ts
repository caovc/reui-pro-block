export interface WishlistCollection {
  id: string;
  name: string;
  description: string;
  updated: string;
  daysAgo: number;
  shared: boolean;
  products: WishlistProduct[];
  coverCount?: number;
}
const collectionFashion = [...savedStudio, ...savedEssentials];
function collectionItems(id: string, count: number, offset: number) {
  return Array.from({ length: count }, (_, index) => ({
    ...collectionFashion[(index + offset) % collectionFashion.length],
    id: `${id}-${index}`,
    stock: 10,
    signal: undefined,
    note: "Saved to this collection",
  }));
}
